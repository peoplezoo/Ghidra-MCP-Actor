"""
MCP (Model Context Protocol) Server for Ghidra Analysis

This module implements an MCP server that exposes Ghidra analysis tools
to AI agents for interactive malware analysis.
"""

import os
import json
import logging
import subprocess
from typing import Any, Dict, List, Optional
from pathlib import Path

import yara
from mcp.server import Server
from mcp.server.stdio import stdio_server
from mcp.types import Tool, TextContent

from src.ghidra.parsers import GhidraAnalysisData

logger = logging.getLogger(__name__)


class GhidraMCPServer:
    """
    MCP Server exposing Ghidra analysis tools to AI agents.
    """

    def __init__(self, analysis_data_path: str, binary_path: Optional[str] = None):
        """
        Initialize the MCP server with analysis data.

        Args:
            analysis_data_path: Path to ghidra_analysis.json
            binary_path: Optional path to original binary for YARA scanning
        """
        self.analysis_data = GhidraAnalysisData(analysis_data_path)
        self.binary_path = binary_path
        self.server = Server("ghidra-analysis")

        # Register tool handlers
        self._register_tools()

        logger.info("Initialized Ghidra MCP Server")

    def _register_tools(self):
        """Register all MCP tools."""

        # Define all available tools
        tools = [
            Tool(
                name="list_functions",
                description=(
                    "List all functions identified in the binary with their names, "
                    "addresses, and signatures. Optionally filter external functions."
                ),
                inputSchema={
                    "type": "object",
                    "properties": {
                        "limit": {
                            "type": "integer",
                            "description": "Maximum number of functions to return",
                            "default": 100,
                        },
                        "filter_external": {
                            "type": "boolean",
                            "description": "Filter out external/thunk functions",
                            "default": True,
                        },
                    },
                },
            ),
            Tool(
                name="get_function",
                description=(
                    "Get detailed information about a specific function by name or address, "
                    "including decompiled pseudocode and called functions."
                ),
                inputSchema={
                    "type": "object",
                    "properties": {
                        "identifier": {
                            "type": "string",
                            "description": "Function name or address",
                        },
                    },
                    "required": ["identifier"],
                },
            ),
            Tool(
                name="decompile",
                description=(
                    "Get decompiled pseudocode for a specific function. "
                    "Returns C-like pseudocode generated by Ghidra's decompiler."
                ),
                inputSchema={
                    "type": "object",
                    "properties": {
                        "function": {
                            "type": "string",
                            "description": "Function name or address to decompile",
                        },
                    },
                    "required": ["function"],
                },
            ),
            Tool(
                name="search",
                description=(
                    "Search for a pattern in decompiled code across all functions. "
                    "Supports regex patterns and plain text search. Useful for finding "
                    "specific API calls, string references, or code patterns."
                ),
                inputSchema={
                    "type": "object",
                    "properties": {
                        "pattern": {
                            "type": "string",
                            "description": "Regex pattern or text to search for",
                        },
                        "case_sensitive": {
                            "type": "boolean",
                            "description": "Whether search is case sensitive",
                            "default": False,
                        },
                    },
                    "required": ["pattern"],
                },
            ),
            Tool(
                name="strings",
                description=(
                    "Extract and search strings from the binary. Can search for specific "
                    "patterns in strings (URLs, file paths, error messages, etc.)"
                ),
                inputSchema={
                    "type": "object",
                    "properties": {
                        "pattern": {
                            "type": "string",
                            "description": "Optional pattern to filter strings",
                        },
                        "limit": {
                            "type": "integer",
                            "description": "Maximum number of strings to return",
                            "default": 100,
                        },
                    },
                },
            ),
            Tool(
                name="xrefs",
                description=(
                    "Find cross-references to a function (i.e., which functions call it). "
                    "Useful for tracing program flow and understanding function usage."
                ),
                inputSchema={
                    "type": "object",
                    "properties": {
                        "symbol": {
                            "type": "string",
                            "description": "Function name or address to find references to",
                        },
                    },
                    "required": ["symbol"],
                },
            ),
            Tool(
                name="imports",
                description=(
                    "List imported functions from external libraries. "
                    "Optionally filter by library name or search for suspicious imports."
                ),
                inputSchema={
                    "type": "object",
                    "properties": {
                        "library": {
                            "type": "string",
                            "description": "Optional library name to filter by",
                        },
                        "suspicious_only": {
                            "type": "boolean",
                            "description": "Only show potentially malicious imports",
                            "default": False,
                        },
                    },
                },
            ),
            Tool(
                name="yara_scan",
                description=(
                    "Scan the binary with YARA rules to detect malware signatures. "
                    "Provide YARA rules as text or reference a ruleset name."
                ),
                inputSchema={
                    "type": "object",
                    "properties": {
                        "rules": {
                            "type": "string",
                            "description": "YARA rules text or ruleset name",
                        },
                    },
                    "required": ["rules"],
                },
            ),
            Tool(
                name="summary",
                description=(
                    "Get a comprehensive summary of the binary analysis including "
                    "statistics, suspicious findings, and key metadata."
                ),
                inputSchema={"type": "object", "properties": {}},
            ),
        ]

        # Register list_tools handler
        @self.server.list_tools()
        async def list_tools() -> List[Tool]:
            return tools

        # Register call_tool handler
        @self.server.call_tool()
        async def call_tool(name: str, arguments: Dict[str, Any]) -> List[TextContent]:
            logger.info(f"Tool called: {name} with args: {arguments}")

            try:
                if name == "list_functions":
                    result = self._list_functions(
                        limit=arguments.get("limit", 100),
                        filter_external=arguments.get("filter_external", True),
                    )
                elif name == "get_function":
                    result = self._get_function(arguments["identifier"])
                elif name == "decompile":
                    result = self._decompile(arguments["function"])
                elif name == "search":
                    result = self._search(
                        pattern=arguments["pattern"],
                        case_sensitive=arguments.get("case_sensitive", False),
                    )
                elif name == "strings":
                    result = self._strings(
                        pattern=arguments.get("pattern"),
                        limit=arguments.get("limit", 100),
                    )
                elif name == "xrefs":
                    result = self._xrefs(arguments["symbol"])
                elif name == "imports":
                    result = self._imports(
                        library=arguments.get("library"),
                        suspicious_only=arguments.get("suspicious_only", False),
                    )
                elif name == "yara_scan":
                    result = self._yara_scan(arguments["rules"])
                elif name == "summary":
                    result = self._summary()
                else:
                    result = {"error": f"Unknown tool: {name}"}

                return [TextContent(type="text", text=json.dumps(result, indent=2))]

            except Exception as e:
                logger.error(f"Error executing tool {name}: {e}", exc_info=True)
                return [
                    TextContent(
                        type="text",
                        text=json.dumps({"error": str(e)}, indent=2),
                    )
                ]

    def _list_functions(self, limit: int = 100, filter_external: bool = True) -> Dict:
        """List functions."""
        funcs = self.analysis_data.list_functions(limit, filter_external)
        return {
            "total": len(funcs),
            "functions": [
                {
                    "name": f["name"],
                    "address": f["address"],
                    "size": f["size"],
                    "signature": f.get("signature", ""),
                }
                for f in funcs
            ],
        }

    def _get_function(self, identifier: str) -> Dict:
        """Get function details."""
        func = self.analysis_data.get_function(identifier)
        if not func:
            return {"error": f"Function not found: {identifier}"}
        return func

    def _decompile(self, function: str) -> Dict:
        """Get decompiled code for a function."""
        func = self.analysis_data.get_function(function)
        if not func:
            return {"error": f"Function not found: {function}"}

        return {
            "function": func["name"],
            "address": func["address"],
            "decompiled": func.get("decompiled", "// Decompilation not available"),
        }

    def _search(self, pattern: str, case_sensitive: bool = False) -> Dict:
        """Search in decompiled code."""
        matches = self.analysis_data.search_decompiled(pattern, case_sensitive)
        return {"pattern": pattern, "matches": matches, "count": len(matches)}

    def _strings(self, pattern: Optional[str] = None, limit: int = 100) -> Dict:
        """Extract and search strings."""
        if pattern:
            strings = self.analysis_data.search_strings(pattern)
        else:
            strings = self.analysis_data.strings[:limit]

        return {"total": len(strings), "strings": strings}

    def _xrefs(self, symbol: str) -> Dict:
        """Get cross-references."""
        xrefs = self.analysis_data.get_xrefs_to_function(symbol)
        return {"symbol": symbol, "xrefs": xrefs, "count": len(xrefs)}

    def _imports(
        self, library: Optional[str] = None, suspicious_only: bool = False
    ) -> Dict:
        """List imports."""
        if suspicious_only:
            imports = self.analysis_data.get_suspicious_imports()
        elif library:
            imports = self.analysis_data.imports_by_lib.get(library, [])
        else:
            imports = self.analysis_data.imports

        return {"total": len(imports), "imports": imports}

    def _yara_scan(self, rules: str) -> Dict:
        """Run YARA scan on binary."""
        if not self.binary_path or not os.path.exists(self.binary_path):
            return {"error": "Binary file not available for YARA scanning"}

        try:
            # Compile YARA rules
            compiled_rules = yara.compile(source=rules)

            # Scan binary
            matches = compiled_rules.match(self.binary_path)

            results = []
            for match in matches:
                results.append({
                    "rule": match.rule,
                    "namespace": match.namespace,
                    "tags": match.tags,
                    "strings": [
                        {
                            "identifier": s[1],
                            "data": s[2].decode("utf-8", errors="replace"),
                            "offset": s[0],
                        }
                        for s in match.strings
                    ],
                })

            return {"matches": results, "count": len(results)}

        except yara.SyntaxError as e:
            return {"error": f"YARA syntax error: {e}"}
        except Exception as e:
            return {"error": f"YARA scan failed: {e}"}

    def _summary(self) -> Dict:
        """Get analysis summary."""
        return self.analysis_data.get_summary()

    async def run(self):
        """Run the MCP server using stdio transport."""
        logger.info("Starting Ghidra MCP Server...")
        async with stdio_server() as (read_stream, write_stream):
            await self.server.run(
                read_stream,
                write_stream,
                self.server.create_initialization_options(),
            )


async def start_mcp_server(analysis_json: str, binary_path: Optional[str] = None):
    """
    Start the MCP server.

    Args:
        analysis_json: Path to ghidra_analysis.json
        binary_path: Optional path to binary for YARA scanning
    """
    server = GhidraMCPServer(analysis_json, binary_path)
    await server.run()
